/// Width of a text run of `n` glyphs at cap height `h`.
#[must_use]
#[allow(clippy::cast_precision_loss)]
pub fn text_width(n: usize, h: f32) -> f32 {
    if n == 0 {
        return 0.0;
    }
    let s = h / GH;
    (n as f32 * GW + (n as f32 - 1.0) * GAP) * s
}

/// Polylines of `text` centred on `(cx, cy)` with cap height `h`.
#[must_use]
pub fn layout(text: &str, cx: f32, cy: f32, h: f32) -> Vec<Vec<P>> {
    let n = text.chars().count();
    let s = h / GH;
    let x0 = cx - text_width(n, h) / 2.0;
    let y0 = cy - h / 2.0;
    let mut out = Vec::new();
    let mut x = x0;
    for c in text.chars() {
        for line in glyph(c) {
            out.push(line.iter().map(|p| [x + p[0] * s, y0 + p[1] * s]).collect());
        }
        x += (GW + GAP) * s;
    }
    out
}
