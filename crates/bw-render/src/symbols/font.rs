/// Width of a text run of `n` glyphs at cap height `h`.
#[must_use]
#[allow(clippy::cast_precision_loss)]
pub fn text_width(n: usize, h: f32) -> f32 {
    if n == 0 {
        return 0.0;
    }
    let s = h / GH;
    (n as f32 * GW + (n as f32 - 1.0) * GAP) * s
}

